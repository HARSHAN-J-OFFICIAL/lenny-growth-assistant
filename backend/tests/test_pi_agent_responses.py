def test_12_citation_preservation():
    """Verify timestamps, URLs, and guest attributions are preserved in parsed result."""
    client = PiAgentClient()
    citations_in = [
        {
            "guest": "Elena Verna 2.0",
            "speaker": "Lenny",
            "episode_title": "The ultimate guide to product-led sales",
            "episode_slug": "elena-verna-20",
            "timestamp_url": "https://www.youtube.com/watch?v=bxghtN-OlJQ&t=69s",
            "start_timestamp": "00:01:09",
            "score": 0.0312,
        }
    ]
    parsed = client._parse_result({"content": "Answer", "citations": citations_in}, "ollama", "llama3.2")
    assert len(parsed.citations) == 1
    assert parsed.citations[0]["start_timestamp"] == "00:01:09"
    assert "https://www.youtube.com/watch?v=bxghtN-OlJQ&t=69s" in parsed.citations[0]["timestamp_url"]


