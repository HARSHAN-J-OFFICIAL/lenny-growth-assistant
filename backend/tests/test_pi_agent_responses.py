@pytest.mark.asyncio
async def test_04_person_absent_from_corpus():
    """Verify querying an entity absent from the transcripts does not invent citations."""
    result = await pi_agent_client.run(
        message="Who is Zyzyx McQwerty?",
        provider="ollama",
        model_name="llama3.2",
    )
    assert result.content != "No response generated by agent."
    content_lower = result.content.lower().replace("’", "'")
    # Must state naturally that no evidence was found or ask for context
    assert any(term in content_lower for term in [
        "couldn't find", "could not find", "not found", "provide more context",
        "no evidence", "not discussed", "not covered", "unable to find"
    ])


def test_05_valid_answer_after_tool_calls():
    """Verify parser extracts substantive response after tool execution trace."""
    client = PiAgentClient()
    mock_data = {
        "content": "Brian Chesky shared insights on founder-mode leadership.",
        "citations": [{"guest": "Brian Chesky", "episode_title": "Founder Mode", "timestamp_url": "https://youtu.be/123"}],
        "tool_calls_trace": [{"tool": "search_podcast_transcripts", "params": {"query": "Brian Chesky"}}],
        "provider": "ollama",
        "model_name": "llama3.2",
        "evidence_status": "sufficient",
    }
    parsed = client._parse_result(mock_data, "ollama", "llama3.2")
    assert parsed.content == "Brian Chesky shared insights on founder-mode leadership."
    assert len(parsed.citations) == 1
    assert parsed.evidence_status == "sufficient"


