def test_14_no_exposure_of_internal_errors_or_credentials():
    """Verify API keys and tracebacks are never placed into user content."""
    client = PiAgentClient()
    mock_leaky_data = {
        "content": "⚠️ Provider Authentication Notice: The API key for groq is invalid. Please verify your credentials.",
        "citations": [],
        "provider": "groq",
        "model_name": "openai/gpt-oss-20b",
    }
    parsed = client._parse_result(mock_leaky_data, "groq", "openai/gpt-oss-20b")
    # Check that raw keys like gsk_ are not exposed
    assert "gsk_" not in parsed.content
    assert "sk-" not in parsed.content
    assert "Traceback (most recent call last)" not in parsed.content
