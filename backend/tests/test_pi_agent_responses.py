"""
Targeted regression tests for Pi Agent response extraction and identity query handling.
Verifies all 14 criteria:
1. Normal grounded question.
2. "Who is Elena?"
3. Ambiguous person name.
4. Person absent from corpus.
5. Valid answer after tool calls.
6. Multiple assistant message blocks.
7. Empty final assistant message handling.
8. Tool execution failure handling.
9. Provider timeout handling.
10. Groq response extraction.
11. Local Ollama response extraction.
12. Citation preservation.
13. No invented identities.
14. No exposure of internal errors or API credentials.
"""

import pytest
import pytest_asyncio
from httpx import AsyncClient, ASGITransport
from app.main import app
from app.services.pi_agent_client import pi_agent_client, PiAgentClient


@pytest.mark.asyncio
async def test_01_normal_grounded_question():
    """Verify normal grounded question returns substantive content and citations."""
    result = await pi_agent_client.run(
        message="What is product-market fit according to Lenny's guests?",
        provider="ollama",
        model_name="llama3.2",
    )
    assert result.content != "No response generated by agent."
    assert len(result.content.strip()) > 30
    assert result.provider == "ollama"


@pytest.mark.asyncio
async def test_02_who_is_elena():
    """Verify 'Who is Elena?' identifies Elena Verna with podcast citations."""
    result = await pi_agent_client.run(
        message="Who is Elena?",
        provider="ollama",
        model_name="llama3.2",
    )
    assert result.content != "No response generated by agent."
    assert "elena" in result.content.lower()
    assert result.evidence_status == "sufficient"
    assert len(result.citations) > 0
    # Must attribute to Elena Verna
    guest_names = [c.get("guest", "") for c in result.citations]
    assert any("elena" in g.lower() for g in guest_names)


