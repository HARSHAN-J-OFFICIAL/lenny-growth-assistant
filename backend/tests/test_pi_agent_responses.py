def test_07_empty_final_assistant_message_recovery():
    """Verify empty content is recovered with grounded citations rather than 'No response generated by agent'."""
    client = PiAgentClient()
    mock_empty_with_citations = {
        "content": "",
        "citations": [{"guest": "Elena Verna", "episode_title": "Product-Led Sales", "timestamp_url": "https://youtu.be/789"}],
        "tool_calls_trace": [{"tool": "search_podcast_transcripts", "params": {"query": "Elena"}}],
        "provider": "ollama",
        "model_name": "llama3.2",
    }
    parsed = client._parse_result(mock_empty_with_citations, "ollama", "llama3.2")
    assert parsed.content != "No response generated by agent."
    assert parsed.content != ""
    assert "Elena Verna" in parsed.content
    assert len(parsed.citations) == 1

    mock_empty_no_citations = {
        "content": "No response generated by agent.",
        "citations": [],
        "provider": "ollama",
        "model_name": "llama3.2",
    }
    parsed_no_cit = client._parse_result(mock_empty_no_citations, "ollama", "llama3.2")
    assert parsed_no_cit.content != "No response generated by agent."
    assert "couldn't find evidence" in parsed_no_cit.content.lower()


